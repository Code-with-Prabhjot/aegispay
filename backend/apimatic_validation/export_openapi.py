"""Regenerate aegispay_api.openapi.yaml from the FastAPI app (mock mode).

Run from the repo root:  python -m backend.apimatic_validation.export_openapi
Add --check to exit non-zero if the committed file is stale.
"""

import sys
from pathlib import Path

import yaml

from backend.app.config import Settings
from backend.app.main import create_app

OUT = Path(__file__).with_name("aegispay_api.openapi.yaml")


def build_spec() -> dict:
    cfg = Settings(_env_file=None, PAYPAL_MODE="mock", DATABASE_URL="sqlite:///:memory:")
    spec = create_app(cfg).openapi()
    # FastAPI 0.110+ emits 3.1.0; keep as-is (APIMatic supports 3.0/3.1).
    return spec


def render() -> str:
    return "# Generated by backend/apimatic_validation/export_openapi.py - do not edit by hand.\n" + yaml.safe_dump(
        build_spec(), sort_keys=False, allow_unicode=True
    )


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text else 1)
    OUT.write_text(text)
    print(f"wrote {OUT}")
